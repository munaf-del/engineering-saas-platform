async function capturePopulatedArtifacts(page, populatedFixture) {
  const multiPileRoute = `/projects/${populatedFixture.project.id}/pile-groups/${populatedFixture.group.id}/multi-pile`;
  await openPricingTab(page, multiPileRoute);

  await page.getByText('Type Quantity Summary', { exact: true }).scrollIntoViewIfNeeded();
  await page.waitForTimeout(500);

  const pricingTabShot = path.join(outDir, 'populated-pricing-tab.png');
  await page.screenshot({ path: pricingTabShot, fullPage: true });

  const xlsxDownloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export Pricing XLSX', exact: true }).click();
  const xlsxDownload = await xlsxDownloadPromise;
  const xlsxPath = path.join(outDir, 'populated-pricing-summary.xlsx');
  await xlsxDownload.saveAs(xlsxPath);

  await Promise.all([
    page.waitForURL(/\/multi-pile\/pricing-summary\/print$/, { timeout: 20000 }),
    page.getByRole('button', { name: 'Print Pricing Summary', exact: true }).click(),
  ]);
  await page.getByTestId('pricing-summary-print-document').waitFor({ timeout: 20000 });
  const printPreviewShot = path.join(outDir, 'populated-print-preview.png');
  await page.screenshot({ path: printPreviewShot, fullPage: true });

  await page.emulateMedia({ media: 'print' });
  const pdfPath = path.join(outDir, 'populated-pricing-summary.pdf');
  await page.pdf({
    path: pdfPath,
    format: 'A4',
    landscape: true,
    printBackground: true,
    margin: { top: '12mm', right: '12mm', bottom: '12mm', left: '12mm' },
  });
  await page.emulateMedia({ media: 'screen' });

  const workbookBuffer = fs.readFileSync(xlsxPath);
  const workbook = XLSX.read(workbookBuffer, { type: 'buffer', cellStyles: true });
  const pilePricingSheet = workbook.Sheets['Pile Pricing'];
  const typeQuantitySheet = workbook.Sheets['Type Quantity Summary'];
  const visualSheet = workbook.Sheets['Pile Type Visual Summary'];
  assert.ok(pilePricingSheet, 'Expected Pile Pricing sheet');
  assert.ok(typeQuantitySheet, 'Expected Type Quantity Summary sheet');
  assert.ok(visualSheet, 'Expected Pile Type Visual Summary sheet');
  assert.equal(visualSheet.A1?.v, 'Pile Type');
  assert.equal(visualSheet.B1?.v, 'Section Sketch Note');
  assert.equal(visualSheet.C1?.v, 'Reinforcement Elevation Note');
  assert.equal(visualSheet.D1?.v, 'Structural Section Summary');
  assert.equal(visualSheet.E1?.v, 'Elevation Summary');

  const pilePricingRows = XLSX.utils.sheet_to_json(pilePricingSheet, { defval: '' });
  const typeSummaryRows = XLSX.utils.sheet_to_json(typeQuantitySheet, { defval: '' });
  const visualSummaryRows = XLSX.utils.sheet_to_json(visualSheet, { defval: '' }).filter(
    (row) => row['Pile Type'],
  );

  assert.ok(
    pilePricingRows.some((row) => String(row['Founding / Socket Material']).includes('RCK')),
    'Expected resolved founding/socket material in populated workbook',
  );
  assert.ok(
    pilePricingRows.some((row) => String(row['Adopted Socket Length']).endsWith(' m')),
    'Expected resolved adopted socket length in populated workbook',
  );
  assert.ok(
    pilePricingRows.every((row) => row['Founding / Socket Material'] !== 'Pending'),
    'Populated workbook should not leave socket material pending',
  );
  assert.ok(
    pilePricingRows.every((row) => row['Structural Section Summary'] !== 'Pending'),
    'Populated workbook should not leave structural section summary pending',
  );
  assert.ok(
    typeSummaryRows.every((row) => row['Typical Socket Material'] !== 'Pending'),
    'Populated type quantity summary should not leave socket material pending',
  );

  const workbookProofShot = path.join(outDir, 'populated-xlsx-workbook-proof.png');
  const workbookProofPage = await page.context().newPage();
  await workbookProofPage.setViewportSize({ width: 1680, height: 1800 });
  await workbookProofPage.setContent(
    workbookProofHtml({
      pilePricingRows: pilePricingRows.slice(0, 3),
      typeSummaryRows: typeSummaryRows.slice(0, 3),
      visualSummaryRows: visualSummaryRows.slice(0, 2),
    }),
  );
  await workbookProofPage.screenshot({ path: workbookProofShot, fullPage: true });
  await workbookProofPage.close();

  return {
    multiPileRoute,
    printRoute: page.url(),
    pricingTabShot,
    printPreviewShot,
    xlsxPath,
    pdfPath,
    workbookProofShot,
    workbookSheets: workbook.SheetNames,
  };
}

