async function createPopulatedFixture(token) {
  const fixture = await createProjectFixture(token, {
    name: 'Pricing Truth Parity Populated',
    code: `PTP-POP-${Date.now()}`,
    description: 'Populated pricing truth-data parity verification fixture',
  });

  await api(`/projects/${fixture.project.id}`, {
    method: 'PATCH',
    token,
    body: {
      metadata: {
        projectSpecifics: populatedProjectSpecifics(),
      },
    },
  });

  let runStatus = 'not-run';
  try {
    const run = await api(
      `/projects/${fixture.project.id}/pile-groups/${fixture.group.id}/multi-pile/envelope-runs`,
      {
        method: 'POST',
        token,
        body: { state: populatedState() },
      },
    );
    runStatus = run?.status ?? 'completed';
  } catch (error) {
    runStatus = `saved-without-envelope: ${error instanceof Error ? error.message : String(error)}`;
    await api(`/projects/${fixture.project.id}/pile-groups/${fixture.group.id}/multi-pile`, {
      method: 'PUT',
      token,
      body: { state: populatedState() },
    });
  }

  const savedState = await api(
    `/projects/${fixture.project.id}/pile-groups/${fixture.group.id}/multi-pile`,
    { token },
  );

  return {
    ...fixture,
    runStatus,
    savedState,
  };
}

