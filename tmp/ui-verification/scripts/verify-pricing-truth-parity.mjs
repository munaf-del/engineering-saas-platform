async function createUserAndOrg() {
  const registerResponse = await fetch(`${apiBase}/auth/register`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ email, password, name: 'Pricing Truth Verification User' }),
  });

  if (!registerResponse.ok && registerResponse.status !== 409) {
    throw new Error(
      `Register failed: ${registerResponse.status} ${await registerResponse.text()}`,
    );
  }

  let auth = await parseJson(registerResponse);
  let token = auth?.accessToken;

  if (!token) {
    const loginResponse = await fetch(`${apiBase}/auth/login`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ email, password }),
    });

    if (!loginResponse.ok) {
      throw new Error(`Login failed: ${loginResponse.status} ${await loginResponse.text()}`);
    }

    auth = await parseJson(loginResponse);
    token = auth?.accessToken;
  }

  assert.ok(token, 'Expected auth token');

  await api('/organisations', {
    method: 'POST',
    token,
    body: { name: 'Pricing Truth Verification Org', slug },
  }).catch(() => null);

  return token;
}

